"""Record the versions actually imported; do not infer compatible versions."""
import importlib.metadata as metadata
import json
from pathlib import Path
from packaging.requirements import Requirement

roots=["qiskit","numpy","scipy","pydantic","fastapi","uvicorn","pytest","httpx"]
versions={}
pending=list(roots)
while pending:
    name=pending.pop()
    key=name.lower().replace('_','-')
    if key in versions: continue
    versions[key]=metadata.version(name)
    for text in metadata.requires(name) or []:
        req=Requirement(text)
        if req.marker is None or req.marker.evaluate({"extra":""}): pending.append(req.name)
path=Path("requirements-tested.txt")
path.write_text("# Observed runtime and test dependency closure; generated by scripts/export_environment.py\n"+"\n".join(f"{k}=={v}" for k,v in sorted(versions.items()))+"\n",encoding="utf-8")
print(json.dumps(versions,indent=2))
